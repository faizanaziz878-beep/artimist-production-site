import { readFile, writeFile, access, rm } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const publicDir = join(root, 'public', 'adu');
const generatedModule = join(root, 'app', 'adu', 'adu-assets.generated.ts');
const names = [
  'adu-hero',
  'adu-floor-plan',
  'adu-elevations',
  'adu-sections',
  'adu-living',
  'adu-garage-plan',
];

const assets = {};

for (const name of names) {
  const source = join(publicDir, `${name}.b64`);
  try {
    await access(source);
    assets[`${name}.svg`] = (await readFile(source, 'utf8')).trim();

    // Remove files created by the older wrapper approach so public files
    // cannot shadow the route handler below during local or CI builds.
    await rm(join(publicDir, `${name}.svg`), { force: true });
    await rm(join(publicDir, `${name}.webp`), { force: true });
  } catch (error) {
    console.error(`Unable to prepare ${name}`, error);
    process.exitCode = 1;
  }
}

// The cinematic exterior currently reuses the approved hero artwork.
assets['adu-exterior.svg'] = assets['adu-hero.svg'];
await rm(join(publicDir, 'adu-exterior.svg'), { force: true });

const moduleSource = `// Generated by scripts/decode-adu-assets.mjs before build.\n// The values are WebP bytes encoded as base64; the route handler decodes\n// them and returns image/webp directly so Safari never has to decode a\n// WebP nested inside an SVG.\nexport const aduAssets: Record<string, string> = ${JSON.stringify(assets)};\n`;
await writeFile(generatedModule, moduleSource, 'utf8');

if (process.exitCode) process.exit(process.exitCode);
console.log('Prepared ADU raster route assets.');
